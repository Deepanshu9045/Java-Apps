    private void loadSubjectName(){
        
        String sql = "SELECT subject_name FROM mst_table";

        try {
            PreparedStatement statement = connection.prepareStatement(sql);
            ResultSet result = statement.executeQuery();
            
            while(result.next()){
                comboSubjectName.addItem(result.getString("subject_name"));
            }

        } catch (SQLException e){
                 Logger.getLogger(StudentForm.class.getName()).log(Level.SEVERE,null,e);
            }
    } 
    
private void saveDetails(){
    String name = txtApplicantName.getText();
    String subject = comboSubjectName.getSelectedItem().toString();
    double marks = Double.parseDouble(txtGraduationMarks.getText());
    String gender = comboGender.getSelectedItem().toString();
    
    if(subject.equalsIgnoreCase("Math") && marks < 55.0){
        javax.swing.JOptionPane.showMessageDialog(this,"Marks must be at least 55% for Math");
    }
    if(subject.equalsIgnoreCase("English") && marks < 60.0){
        javax.swing.JOptionPane.showMessageDialog(this,"Marks must be at least 60% for Math");
    }
    
    try {
        String sql = "Select subject_id form mst_table where subject_name = ?";
        PreparedStatement statement = connection.prepareStatement(sql);
        statement.setString(1, subject);
        ResultSet result = statement.executeQuery();
        
        if(result.next()){
            int subjectId  = result.getInt("subject_id");
            String sqlA = "INSTER INTO transaction (subject_id, applicant_name, gender, date, graduation_marks) VALUES (?,?,?,NOW(),?)";
            PreparedStatement statementA = connection.prepareStatement(sqlA);
            statementA.setInt(1, subjectId);
            statementA.setString(2, name);
            statementA.setString(3, gender);
            statementA.setDouble(4, marks);
            statementA.executeUpdate();
            
            javax.swing.JOptionPane.showMessageDialog(this, "Record Saved Successfully!");

            
        }
    } catch(SQLException e){
        Logger.getLogger(StudentForm.class.getName()).log(Level.SEVERE,null,e);
        
    }
    
}
    
private void loadReport() {
    String selectedSubject = comboSubjectName.getSelectedItem().toString();
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);

    String sql = "SELECT t.applicant_name, t.graduation_marks FROM transaction t JOIN mst_table m ON t.subject_id = m.subject_id WHERE m.subject_name = ?";

    try {
        PreparedStatement statement = connection.prepareStatement(sql);
        statement.setString(1, selectedSubject);
        ResultSet result = statement.executeQuery();

        int srNo = 1;
        while (result.next()) {
            String applicantName = result.getString("applicant_name");
            double marks = result.getDouble("graduation_marks");
            model.addRow(new Object[]{srNo++, applicantName, marks});
        }

    } catch (SQLException e) {
        Logger.getLogger(StudentForm.class.getName()).log(Level.SEVERE, null, e);
    }
}
    
    
