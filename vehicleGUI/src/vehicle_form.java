    public void saveDetail(){
        String query = "Insert into service_tble (model_id, vehicle_no, current_km_reading, service_date, service_charge) value (?,?,?,?,?)";
        try {
            PreparedStatement statement = connection.prepareStatement(query);
            
            String model = (String) combo.getSelectedItem();
            int model_no = Integer.parseInt(model.split("-")[0].trim());
            statement.setInt(1, model_no);
            
            String VehicleNo= txtVehicleNo.getText();
            statement.setString(2, VehicleNo);
            
            String CurrentKmReading= txtCurrentKm.getText();
            statement.setString(3, CurrentKmReading);
            
            java.util.Date date= (java.util.Date) jDateChooser1.getDate();
            java.sql.Date sqlDate= new java.sql.Date(date.getTime());
            statement.setDate(4, sqlDate);
            
            int serviceCharge = getServiceCharge(model_no);
            statement.setInt(5, serviceCharge);
            statement.executeUpdate();
         
            JOptionPane.showMessageDialog(combo, "Data saved successfully!!!!");
            
        }
        
        catch (SQLException ex) {
            Logger.getLogger(vehicle_form.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    
public int getServiceCharge(int modelId) {
    String query = "SELECT service_charge FROM mst_model WHERE model_id = ?";

    try {
        PreparedStatement statement = connection.prepareStatement(query);
        statement.setInt(1, modelId);

        ResultSet result = statement.executeQuery();

        if (result.next()) {
            return result.getInt("service_charge");
        }

    } catch (SQLException ex) {
        Logger.getLogger(vehicle_form.class.getName())
              .log(Level.SEVERE, null, ex);
    }

    return 0;
}
    
    public void getModelDetails(){
        String query = "select model_id, model_name from mst_model";
        try {
            PreparedStatement statement = connection.prepareStatement(query);
            ResultSet result = statement.executeQuery();
            while(result.next()){
                combo.addItem(result.getInt("model_id")+"-"+result.getString("model_name"));
            }
        }catch(SQLException ex) {
            Logger.getLogger(vehicle_form.class.getName()).log(Level.SEVERE,null,ex);
            
        }
    }
    

    
private void report() {
    DefaultTableModel model = new DefaultTableModel(
        new Object[]{"Sr No", "Model Name", "Vehicle No", "Service Charge"}, 0
    );

    String query = "SELECT s.trans_id, m.model_name, s.vehicle_no, s.service_charge " +
                   "FROM service_tble s " +
                   "JOIN mst_model m ON s.model_id = m.model_id";

    try {
        PreparedStatement statement = connection.prepareStatement(query);
        ResultSet result = statement.executeQuery();

        while (result.next()) {
            model.addRow(new Object[]{
                result.getInt("trans_id"),
                result.getString("model_name"),
                result.getString("vehicle_no"),
                result.getInt("service_charge")
            });
        }

        jTable1.setModel(model);

    } catch (SQLException ex) {
        Logger.getLogger(vehicle_form.class.getName())
              .log(Level.SEVERE, null, ex);
    }
}

